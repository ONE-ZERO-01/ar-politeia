def _read(relative: str) -> str:
    return (REPO_ROOT / relative).read_text(encoding="utf-8")


def _parser_keys() -> set[str]:
    return set(re.findall(r'key == "([a-z0-9_]+)"', _read(CONFIG_CPP)))


def _field_defaults() -> dict[str, str]:
    fields = re.findall(
        r"^\s{4}([A-Za-z_:<>0-9 ]+?)\s+([A-Za-z0-9_]+)\s*=\s*([^;]+);",
        _read(CONFIG_HPP),
        re.M,
    )
    return {name: default.strip() for _, name, default in fields}


def _key_to_field() -> dict[str, str]:
    return dict(
        re.findall(r'key == "([a-z0-9_]+)"\)\s*cfg\.([A-Za-z0-9_]+)', _read(CONFIG_CPP))
    )


def _reference_config_values(tmp_path, monkeypatch) -> dict[str, str]:
    """Generate the reference cfg the way the driver does, and parse it."""
    monkeypatch.setattr(run_landscape_study, "PROJECT_ROOT", tmp_path)
    config = {
        "seeds": [11],
        "population": 16,
        "grid_shape": [16, 16],
        "bounds": [0.0, 100.0, 0.0, 100.0],
        "dt": 0.005,
        "total_time": 1.0,
        "output_time_interval": 0.5,
        "temperature": 0.5,
        "friction": 1.0,
        "social_strength": 0.0,
        "exchange_rate": 0.5,
        "exchange_noise_strength": 0.05,
        "exchange_reversion_rate": 1.0,
        "epsilon_log_sigma": 0.5,
        "wealth_decay_rate": 0.02,
        "base_production": 0.01,
        "mean_wealth": 5.0,
        "terrain_production_scale": 1.0,
        "terrain_force_scale": 1.0,
        "strict_numerics": True,
        "confirmative_mode": True,
    }
    specs = run_landscape_study.prepare_inputs(
        REFERENCE_EXPERIMENT, config, tmp_path / "reference"
    )
    assert specs, "the driver produced no run specs"
    cfg_path = run_landscape_study.project_path(specs[0]["cpp_config"])
    values: dict[str, str] = {}
    for line in cfg_path.read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip()
    return values


@pytest.fixture(scope="module")
def reference_cfg(tmp_path_factory):
    """Generated once; the generator is pure with respect to the repo."""
    return _reference_config_values(
        tmp_path_factory.mktemp("config-coverage"), pytest.MonkeyPatch()
    )


def _classified() -> dict[str, str]:
    """key -> category, for every key outside the reference cfg."""
    table: dict[str, str] = {}
    for switch, keys in GATED_BY_SWITCH.items():
        for key in keys:
            table[key] = f"gated:{switch}"
    for key in IC_SUPERSEDED:
        table[key] = "ic-superseded"
    for key in BRANCH_INERT:
        table[key] = "branch-inert"
    for key in SENTINEL:
        table[key] = "sentinel"
    for key in NO_CONSUMER:
        table[key] = "no-consumer"
    for key in LEGACY_ALIAS:
        table[key] = "legacy-alias"
    for key in EFFECTIVE_UNDECLARED:
        table[key] = "effective-undeclared"
    return table


def test_every_parser_key_is_classified_exactly_once(reference_cfg):
    parser_keys = _parser_keys()
    table = _classified()
    declared = set(reference_cfg)

    assert len(table) == len(set(table)), "a key is classified twice"
    assert declared <= parser_keys, (
        "the driver emits a cfg key the simulator cannot parse: "
        f"{sorted(declared - parser_keys)}"
    )
    assert declared.isdisjoint(table), (
        "a key is both declared in the reference cfg and filed under an "
        f"inert/gap category: {sorted(declared & set(table))}"
    )
    unclassified = parser_keys - declared - set(table)
    assert not unclassified, (
        "new simulator knob(s) without an audited category -- decide whether "
        f"the reference cfg declares them or which switch gates them: "
        f"{sorted(unclassified)}"
    )
    stale = set(table) - parser_keys
    assert not stale, f"audit table lists keys config.cpp does not parse: {sorted(stale)}"


def test_reference_cfg_pins_every_gating_switch_off(reference_cfg):
    for switch in GATED_BY_SWITCH:
        assert switch in reference_cfg, (
            f"{switch} is the gate for {len(GATED_BY_SWITCH[switch])} audited "
            "keys but the reference cfg does not pin it"
        )
        assert reference_cfg[switch] == "false", (
            f"{switch} is not false in the reference cfg, so every key filed "
            "under it is reachable and the audit must be redone"
        )


def test_no_gated_or_gap_key_is_emitted_by_the_driver(reference_cfg):
    table = _classified()
    emitted = sorted(set(table) & set(reference_cfg))
    assert not emitted, (
        "the driver now emits keys the audit filed as inert/gap; either the "
        f"gap is closed (update the table) or the build is inconsistent: {emitted}"
    )


def test_effective_defaults_keep_their_anchors(reference_cfg):
    defaults = _field_defaults()
    key_to_field = _key_to_field()
    constants = _read(CONSTANTS_HPP)

    # The recorded gaps must stay undeclared: pinning one would change whether
    # the reference cfg determines the run, and that change has to be deliberate.
    for key in EFFECTIVE_UNDECLARED:
        assert key not in reference_cfg, f"{key} is now declared in the cfg"

    density_default = defaults[key_to_field["density_radius"]]
    assert density_default == EFFECTIVE_UNDECLARED["density_radius"][0], (
        "density_radius changed default; the recorded cell geometry (and thus "
        "the exchange pair order) changed with it"
    )
    assert (
        "std::max(cfg.interaction_range, cfg.density_radius)"
        in _read(MAIN_CPP)
    ), "the density_radius -> cell_cutoff coupling moved; re-audit the gap"

    culture_default = defaults[key_to_field["culture_dim"]]
    assert culture_default == "constants::DEFAULT_CULTURE_DIM"
    assert re.search(r"DEFAULT_CULTURE_DIM\s*=\s*2\s*;", constants), (
        "DEFAULT_CULTURE_DIM changed; the number of N(0,1) draws the IC loader "
        "consumes per particle changed with it"
    )
    assert "dist_cv(rng)" in _read(IC_LOADER), (
        "the IC loader no longer draws a fallback culture vector; re-audit "
        "how many RNG values a missing c* column consumes"
    )


def test_shared_and_declared_keys_are_never_filed_as_gated(reference_cfg):
    # Several knobs feed two parameter structs at once (e.g.
    # `culture_mate_threshold` goes to both the mating and the culture struct,
    # `interaction_range` to force, exchange, reproduction and culture). A key
    # is only filed as gated when *every* consumer sits behind that switch, so
    # Several knobs feed two parameter structs at once: `interaction_range`
    # goes to force, exchange, reproduction and culture, so it is declared;
    # `culture_mate_threshold` goes to mating *and* culture, both of which the
    # reference cfg switches off, so filing it under one switch is sound.
    table = _classified()
    for key in ("interaction_range", "exchange_rate"):
        assert key in reference_cfg
        assert key not in table, f"{key} has a consumer outside its switch"
    assert all(
        switch in ("culture_enabled", "reproduction_enabled")
        for switch, keys in GATED_BY_SWITCH.items()
        if "culture_mate_threshold" in keys
    )

    for switch, keys in GATED_BY_SWITCH.items():
        assert keys, f"{switch} gates nothing"
        assert len(keys) == len(set(keys)), f"{switch} lists a key twice"
