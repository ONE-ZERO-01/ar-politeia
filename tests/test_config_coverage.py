"""Config-key coverage: every simulator knob is either declared, gated, or a known gap.

The reference configuration that E1-C4/E2-C4 actually runs is a 47-key
``politeia.cfg`` generated by the experiment driver, while ``config.cpp`` accepts
185 keys. The other 138 therefore take their values from the C++ in-class
initializers, and nothing in the repository said which of those 138 are harmless
and which are live. That is the same structural gap that produced S16/S17/S18:
a channel nobody rejected at the entrance can be active without anyone noticing.

This module makes the inventory mechanical. It parses the parser keys out of
``config.cpp``, derives the effective default of each field from ``config.hpp``,
generates the reference ``politeia.cfg`` with the driver itself, and then
requires **every** parser key to fall in exactly one audited category:

* declared in the reference cfg,
* gated by a module switch the reference cfg pins to ``false``,
* superseded by the IC file or by an untaken code branch,
* a sentinel/alias, or a field with no consumer at all,
* or a **documented gap**: reachable and non-neutral while undeclared.

Adding a new knob to ``config.cpp`` without classifying it fails test 1, so the
audit cannot silently fall behind the code. The remaining tests pin the
assumptions the table rests on (switches stay off, generated keys stay declared,
the two recorded gaps keep their exact default values). Everything here is
static: it reads C++/Python sources and writes only into ``tmp_path``.
"""

